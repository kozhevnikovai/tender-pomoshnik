// Число прописью → число (1–999): «пятнадцати» → 15, «тридцать (30)» и т. п.
const UNITS: [RegExp, number][] = [
  [/^одн|^один|^перв/, 1], [/^дв(?:а|е|ух|умя)$|^втор/, 2], [/^тр(?:и|ех|ём|ем|емя)$|^трет/, 3], [/^четыр(?:е|ех|ём|ьмя)$|^четв/, 4],
  [/^пят(?:ь|и|ью)$|^пят(?!надц|ьдес|исот|ьсот)/, 5], [/^шест(?:ь|и|ью)$/, 6], [/^сем(?:ь|и|ью)$|^седьм/, 7], [/^восем(?:ь|и)$|^восьм(?!надц|идес|исот|ьсот)/, 8], [/^девят(?:ь|и|ью)$/, 9],
];
const TEENS: [RegExp, number][] = [[/^десят/, 10], [/^одиннадцат/, 11], [/^двенадцат/, 12], [/^тринадцат/, 13], [/^четырнадцат/, 14], [/^пятнадцат/, 15], [/^шестнадцат/, 16], [/^семнадцат/, 17], [/^восемнадцат/, 18], [/^девятнадцат/, 19]];
const TENS: [RegExp, number][] = [[/^двадцат/, 20], [/^тридцат/, 30], [/^сорок/, 40], [/^пятьдесят|^пятидесят/, 50], [/^шестьдесят|^шестидесят/, 60], [/^семьдесят|^семидесят/, 70], [/^восемьдесят|^восьмидесят/, 80], [/^девяност/, 90]];
const HUND: [RegExp, number][] = [[/^сто$|^ста$/, 100], [/^двест|^двухсот/, 200], [/^трист|^трехсот/, 300], [/^четырест|^четырехсот/, 400], [/^пятьсот|^пятисот/, 500], [/^шестьсот|^шестисот/, 600], [/^семьсот|^семисот/, 700], [/^восемьсот|^восьмисот/, 800], [/^девятьсот|^девятисот/, 900]];

export function wordsToNumber(s: string): number | null {
  let n = 0, any = false;
  for (const w of s.toLowerCase().replace(/ё/g, "е").split(/\s+/).filter(Boolean)) {
    const hit = [HUND, TEENS, TENS, UNITS].map(t => t.find(([re]) => re.test(w))).find(Boolean);
    if (!hit) { if (/^(рабоч|календар|дн|дней|час|месяц|процент|руб|тыс)/.test(w)) continue; return null; }
    n += hit[1]; any = true;
  }
  return any ? n : null;
}
