// Черновики: запрос на разъяснение и жалоба в ФАС. Только черновики — подаёт человек.
import type { Report, Risk } from "../types.js";
import { fmtSource } from "../docs/quote.js";

const DRAFT = "ЧЕРНОВИК. Подготовлен Тендерным помощником. Это не юридическая консультация: проверьте факты, цитаты и нормы, дополните и подайте самостоятельно.";

export function clarificationDraft(r: Report, company = "[Наименование участника]"): string {
  const qs = r.risks.filter(x => x.question);
  const nmb = r.noticeNumber ?? "[номер извещения]";
  const basis = r.law === "223-ФЗ" ? "ч. 3 ст. 3.2 Федерального закона от 18.07.2011 № 223-ФЗ" : "ч. 5 ст. 42 Федерального закона от 05.04.2013 № 44-ФЗ";
  const lines = [
    DRAFT, "",
    `Запрос о даче разъяснений положений извещения (документации) о закупке № ${nmb}`,
    r.title ? `Объект закупки: ${r.title}` : "",
    "",
    `На основании ${basis} просим разъяснить следующие положения:`,
    "",
    ...(qs.length ? qs.flatMap((x, i) => [`${i + 1}. ${x.question}`, x.source ? `   Положение: «${x.source.quote}» (${fmtSource(x.source)}).` : "", ""]) : ["1. [Сформулируйте вопрос и укажите пункт документации]", ""]),
    `${company}`,
  ];
  return lines.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n");
}

export function complaintDraft(r: Report, applicant = "[Наименование, ИНН, адрес, телефон, e-mail заявителя]"): string {
  const items: Risk[] = r.risks.filter(x => x.complaint);
  const is223 = r.law === "223-ФЗ";
  const head = is223
    ? "В Управление Федеральной антимонопольной службы по [субъект РФ] (жалоба в порядке ст. 18.1 Федерального закона от 26.07.2006 № 135-ФЗ, ч. 10 ст. 3 Федерального закона № 223-ФЗ)"
    : "В Федеральную антимонопольную службу / Управление ФАС по [субъект РФ] (жалоба в порядке ст. 105 Федерального закона от 05.04.2013 № 44-ФЗ)";
  return [
    DRAFT, "",
    head, "",
    `Заявитель: ${applicant}`,
    `Заказчик: ${r.fields.find(f => f.key === "customer")?.value ?? "[наименование, адрес]"}`,
    `Закупка: № ${r.noticeNumber ?? "[номер]"}${r.title ? `, «${r.title}»` : ""}`,
    `Электронная площадка: ${r.fields.find(f => f.key === "platform")?.value ?? "[наименование, адрес]"}`,
    "",
    "ЖАЛОБА",
    "на положения извещения (документации) о закупке",
    "",
    "Заказчиком при осуществлении закупки допущены следующие нарушения:",
    "",
    ...(items.length ? items.flatMap((x, i) => [
      `${i + 1}. ${x.title}.`,
      `   ${x.detail}`,
      x.source ? `   Положение документации: «${x.source.quote}» (${fmtSource(x.source)}).` : "",
      x.law?.length ? `   Норма: ${x.law.map(l => `${l.act}, ${l.ref}`).join("; ")}${x.law.some(l => l.status === "check") ? " — формулировку нормы проверить по первоисточнику" : ""}.` : "",
      "",
    ]) : ["1. [Опишите нарушение, процитируйте положение документации и укажите норму закона]", ""]),
    "Указанные положения нарушают права и законные интересы Заявителя как участника закупки: [опишите, как именно].",
    "",
    "На основании изложенного прошу:",
    "1. Признать жалобу обоснованной.",
    "2. Выдать заказчику предписание об устранении нарушений.",
    is223 ? "" : "3. Приостановить определение поставщика в части заключения контракта до рассмотрения жалобы по существу.",
    "",
    "Приложения: [документ, подтверждающий полномочия лица, подписавшего жалобу; иные документы].",
    "",
    "[Должность, ФИО, подпись — жалоба подписывается электронной подписью и подаётся через ЕИС]",
    "",
    is223 ? "Срок подачи: не позднее 10 дней со дня подведения итогов — проверьте по дате протокола." : "Срок подачи жалобы на положения извещения — до окончания срока подачи заявок.",
  ].filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n");
}
